import { Skeleton } from "@/components/ui/skeleton";

/**
 * 좌석 영역 자리표시자 (Task 030_2).
 *
 * 쓰이는 곳이 둘이다 —
 *  1) seats/loading.tsx: 페이지 진입 직후 (세그먼트 전체가 아직 안 풀렸을 때)
 *  2) seats/page.tsx의 Suspense fallback: 공연·회차·등급은 그렸고 좌석만 기다릴 때
 *
 * 둘이 같은 마크업이어야 한다. 셸 → 본문 → 좌석으로 두 번 교체되는 동안 자리 크기가
 * 달라지면 레이아웃이 두 번 튄다. 그래서 한 컴포넌트로 묶었다.
 *
 * ★ 높이가 CLS를 만들었다 ★
 *   원래 28rem(448px)이었다. 좌석 조회를 Suspense로 분리하자(같은 Task) 이 자리표시자가
 *   화면에 먼저 그려지고 좌석이 나중에 들어오는 구간이 생겼는데, 그때 CLS가
 *   0.0278 → 0.1996으로 뛰었다(6회 중 5회, 구글 기준 0.1을 넘는다).
 *
 *   원인은 푸터다. 실측하면 좌석 영역은 300px 지점에서 시작해 1,114px 높이로 그려지고
 *   푸터는 1,176px에 온다(2,000석, 1350x940 뷰포트). 자리표시자가 448px이면 푸터가
 *   약 800px — 화면 안에 보인다. 좌석이 도착하면 푸터가 +376px 밀리고,
 *   376/940 = 거리 비율 0.4에 영향 영역을 곱하면 CLS 0.2가 된다.
 *
 *   그래서 실제 좌석맵 높이를 맞추려 하지 않는다 — 공연장마다 다르고 서버는 좌석을 받기
 *   전에 그 높이를 모른다. 대신 **두 상태 모두에서 푸터가 접힘선 아래에 있게** 만든다.
 *   화면 밖에서 일어나는 시프트는 CLS에 잡히지 않는다.
 *
 *   100vh - 12rem을 쓰면 940px 뷰포트에서 748px(바닥 1,048px), 768px에서 576px(바닥 876px),
 *   1200px에서 1,008px(바닥 1,308px)이라 어느 쪽에서도 푸터가 화면 밖에 머문다.
 *   12rem은 헤더(3.5rem) + 본문 상단 여백·제목 블록 몫이다.
 */
export function SeatMapSkeleton() {
  return <Skeleton className="min-h-[calc(100vh-12rem)] w-full rounded-xl" />;
}
